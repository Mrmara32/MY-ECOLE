const LANG_NAMES = { fr: 'Français', en: 'English', es: 'Español', it: 'Italiano', ar: 'العربية' };
const RTL_LANGS = ['ar'];

function getCurrentLang() {
  return localStorage.getItem('gs_lang') || 'fr';
}

function t(key) {
  const lang = getCurrentLang();
  return (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) || TRANSLATIONS.fr[key] || key;
}

function setLang(lang) {
  localStorage.setItem('gs_lang', lang);
  applyLangDirection(lang);
  // Recharger l'interface pour appliquer la traduction partout
  if (typeof buildNav === 'function' && currentUser) buildNav();
  if (typeof navigate === 'function' && currentUser) navigate(currentPage);
  if (typeof initLogin === 'function' && !currentUser) applyLoginTranslations();
  const pwdBtn = document.querySelector('#pwd-btn');
  if (pwdBtn) pwdBtn.textContent = '🔒 ' + t('password_menu');
  const logoutBtn = document.querySelector('#logout-btn');
  if (logoutBtn) logoutBtn.textContent = '⎋ ' + t('logout_btn');
  const roleEl = document.querySelector('#sb-role');
  if (roleEl && currentUser) roleEl.textContent = t('role_' + currentUser.role) || currentUser.role;
}

function applyLangDirection(lang) {
  document.documentElement.setAttribute('lang', lang);
  document.documentElement.setAttribute('dir', RTL_LANGS.includes(lang) ? 'rtl' : 'ltr');
  document.body.classList.toggle('rtl', RTL_LANGS.includes(lang));
}

function applyLoginTranslations() {
  const set = (sel, key) => { const el = document.querySelector(sel); if (el) el.textContent = t(key); };
  set('.login-sub', 'login_title');
  set('#l-user', null); // placeholder handled separately
  const userInput = document.querySelector('#l-user');
  if (userInput) userInput.placeholder = t('login_username');
  const passInput = document.querySelector('#l-pass');
  if (passInput) passInput.placeholder = t('login_password');
  set('#login-btn', 'login_btn');
  // Labels au-dessus des champs
  const labels = document.querySelectorAll('#login-form label');
  if (labels[0]) labels[0].textContent = t('login_username');
  if (labels[1]) labels[1].textContent = t('login_password');
}

function langSwitcherHtml(compact = false, elId = 'lang-switcher') {
  const current = getCurrentLang();
  return `<select id="${elId}" class="lang-switcher" onchange="setLang(this.value)" style="${compact?'padding:4px 8px;font-size:12px;':''}border:1px solid var(--g3);border-radius:6px;background:#fff;cursor:pointer">
    ${Object.entries(LANG_NAMES).map(([code,name]) => `<option value="${code}" ${code===current?'selected':''}>${name}</option>`).join('')}
  </select>`;
}

// Appliquer la direction dès le chargement de la page (avant même la connexion)
applyLangDirection(getCurrentLang());
